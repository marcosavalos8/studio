import DOMPurify, { type Config } from "dompurify";
import type { CompanyInfo } from "@/hooks/use-company-info";

// Allowed tags/attributes match exactly what the rich text editor
// (StarterKit: paragraphs, headings, bold/italic, ordered/unordered lists,
// line breaks) can produce — nothing else is ever rendered back from saved
// contract content.
const SANITIZE_CONFIG: Config = {
  ALLOWED_TAGS: [
    "p",
    "strong",
    "em",
    "h1",
    "h2",
    "h3",
    "ul",
    "ol",
    "li",
    "br",
  ],
  ALLOWED_ATTR: [],
};

// Sanitizes clause HTML before it's ever saved to Firestore or rendered
// with dangerouslySetInnerHTML, so a contract's content can never carry
// executable markup regardless of how it got there (editor, template,
// or a future import path).
export function sanitizeContractHtml(html: string): string {
  if (typeof window === "undefined") {
    // DOMPurify needs a DOM; on the server just strip tags defensively.
    // Contracts are only ever written from the client ('use client'
    // components), so this path is a safety net, not the normal case.
    return html.replace(/<[^>]*>/g, "");
  }
  return DOMPurify.sanitize(html, SANITIZE_CONFIG);
}

export type ContractTemplateParams = {
  companyInfo: CompanyInfo;
  clientName: string;
  clientAddress?: string;
  effectiveDateDisplay?: string;
  paymentDueDays?: number;
  lateFeeInterestPercent?: number;
  terminationNoticeDays?: number;
};

const blank = (value: string | number | undefined, suffix = "") =>
  value === undefined || value === null || value === ""
    ? "____________________"
    : `${value}${suffix}`;

// Builds the editable starting content for a new contract, modeled on the
// business's own Master Service Agreement boceto (MSA) — every clause below
// is the provider's existing boilerplate reproduced as-is, not legal advice
// generated for this task. Only the bracketed values above are substituted;
// everything else is the template text verbatim. The result is plain
// editable HTML — the user can freely rewrite any of it afterward.
export function buildContractTemplateHtml(params: ContractTemplateParams): string {
  const { companyInfo } = params;

  const html = `
<h1>MASTER SERVICE AGREEMENT (MSA)</h1>
<p><strong>${escapeHtml(companyInfo.companyName)}</strong></p>
<p><strong>Effective Date:</strong> ${blank(params.effectiveDateDisplay)}</p>
<p><strong>Between Client (Grower):</strong> ${escapeHtml(params.clientName) || "____________________"}</p>
<p>${blank(params.clientAddress)}</p>
<p><strong>And Service Provider (FLC):</strong></p>
<p><strong>${escapeHtml(companyInfo.companyName)}</strong><br>${escapeHtml(companyInfo.address)}<br>(UBI: ${escapeHtml(companyInfo.ubi)} | EIN: ${escapeHtml(companyInfo.ein)} | License: #172-25)</p>

<h2>1. PURPOSE AND SCOPE OF SERVICES</h2>
<p>${escapeHtml(companyInfo.companyName)} ("Provider") agrees to provide agricultural workforce services to the client ("Grower") as requested and agreed upon. These services may include, but are not limited to, harvesting, pruning, thinning, general field labor, tractor operation, and field supervision. Provider operates strictly as an independent Farm Labor Contractor (FLC).</p>

<h2>2. INDEPENDENT CONTRACTOR STATUS &amp; EMPLOYER RESPONSIBILITIES</h2>
<ul>
<li><strong>Exclusive Employer:</strong> Provider is the sole and independent employer of all agricultural workers, supervisors, and equipment operators supplied to the Grower's premises.</li>
<li><strong>Worker Management:</strong> Provider maintains exclusive authority and responsibility for hiring, firing, payroll processing, tax withholdings, worker's compensation (L&amp;I), and compliance with all state and federal employment regulations.</li>
<li><strong>Privacy and Operational Control:</strong> To maintain legal compliance as an independent FLC and protect employee confidentiality, internal personnel records, individual clock-in/clock-out logs, and employee personal identifiers remain strictly proprietary to Provider and will not be transferred to Grower. Grower shall receive aggregated labor reports, crew headcounts, and verified task metrics as outlined herein.</li>
</ul>

<h2>3. MANDATORY LABOR REGULATIONS AND STATUTORY COMPLIANCE (BREAKS &amp; MINIMUM WAGE)</h2>
<ul>
<li><strong>Paid Rest Breaks:</strong> In strict accordance with Washington State law (WAC 296-131-020), Provider is mandated to provide and pay piece-rate workers for mandatory rest breaks at the higher of the regular hourly rate derived from piecework productivity or the statutory minimum wage.</li>
<li><strong>Cost Reimbursement:</strong> Grower acknowledges that statutory labor costs — including paid rest breaks and minimum wage adjustments — are non-negotiable legal operating expenses directly generated by the harvest and field conditions at Grower's property. Grower agrees to fully reimburse these mandatory costs as part of the total labor service billing. These expenses cannot be waived or absorbed contrary to state law.</li>
</ul>

<h2>4. BILLING, INVOICING, AND PAYMENT TERMS</h2>
<ul>
<li><strong>Invoice Structure:</strong> Provider shall issue weekly invoices accompanied by a detailed Labor Report containing task summaries, piece counts, hours worked, and aggregate crew headcounts by task/date.</li>
<li><strong>Payment Due Date:</strong> Payment is due in full within ${blank(params.paymentDueDays, " days")} of the invoice date.</li>
<li><strong>Late Fees and Interest:</strong> Unpaid balances past the agreed-upon terms will incur a late fee interest charge of ${blank(params.lateFeeInterestPercent, "% per month")} (or the maximum rate permitted by Washington law) on the overdue balance until paid in full.</li>
<li><strong>Dispute Resolution:</strong> If Grower disputes any portion of an invoice, Grower must notify Provider in writing within 7 business days of receipt, specifying the exact item in question. Undisputed amounts must be paid by the due date. Refusal to pay mandatory statutory costs (such as state-mandated breaks) shall constitute a material breach of this Agreement.</li>
</ul>

<h2>5. LIABILITY, INDEMNIFICATION, AND INSURANCE</h2>
<ul>
<li><strong>Insurance:</strong> Provider shall maintain valid FLC licensing (#172-25) and active worker's compensation coverage through the Washington Department of Labor &amp; Industries (L&amp;I).</li>
<li><strong>Indemnification:</strong> Grower agrees to indemnify, defend, and hold harmless ${escapeHtml(companyInfo.companyName)}, its owners, and its agents from any claims, liabilities, or damages arising out of Grower's failure to provide a safe working environment compliant with WISHA/OSHA safety standards on Grower's premises.</li>
</ul>

<h2>6. TERM AND TERMINATION</h2>
<ul>
<li><strong>Duration:</strong> This Agreement shall remain in effect for the current agricultural season and shall renew automatically unless terminated.</li>
<li><strong>Termination:</strong> Either party may terminate this Agreement with ${blank(params.terminationNoticeDays, " days")} written notice to the other party. Upon termination, Grower remains fully obligated to pay for all labor services rendered, piecework completed, and statutory costs incurred up to the final date of service.</li>
</ul>

<h2>7. GOVERNING LAW</h2>
<p>This Agreement shall be governed by, construed, and enforced in accordance with the laws of the State of Washington. Any legal action arising from this contract shall be handled within the jurisdiction of the appropriate courts in Washington.</p>

<p><strong>IN WITNESS WHEREOF</strong>, the parties hereto have executed this Master Service Agreement as of the date first written above.</p>

<p><strong>GROWER (CLIENT):</strong></p>
<p>Signature: ____________________________________</p>
<p>Printed Name: ____________________________________</p>
<p>Title: ____________________________________</p>
<p>Date: ____________________________________</p>

<p><strong>SERVICE PROVIDER (${escapeHtml(companyInfo.companyName)}):</strong></p>
<p>Signature: ____________________________________</p>
<p>Printed Name: ____________________________________</p>
<p>Title: ____________________________________</p>
<p>Date: ____________________________________</p>
`.trim();

  return sanitizeContractHtml(html);
}

function escapeHtml(value: string | undefined): string {
  if (!value) return "";
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}
